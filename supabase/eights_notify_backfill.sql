-- ============================================================
-- 既存ユーザー全員の8s通知を初期ONにするバックフィル (実行済み・一度きり)
--
-- 8s通知はオプトイン制で始めたが、方針を「初期ON (オプトアウト)」に変更。
-- 新規ユーザーはオンボーディングのトグル (初期ON) で設定されるため、
-- このスクリプトは移行時の既存ユーザー向けに一度だけ実行した。
-- 既に設定済みのユーザーは上書きしない。
-- BAN中ユーザーにも行は作られるが、送信時に is_banned で除外される。
-- OFFにしたい人は /custom の「通知設定」からいつでも変更できる。
-- ============================================================

INSERT INTO public.eights_notify_prefs (user_id, enabled)
SELECT p.id, true
FROM public.profiles p
ON CONFLICT (user_id) DO NOTHING;
